"use strict";
const assert=require("node:assert/strict"),crypto=require("node:crypto");
const {encodeCBOR}=require("@levischuck/tiny-cbor");
const {Passkeys}=require("./attestation/passkeys");
const {verifyToken}=require("./attestation/verifier");
const b64=b=>Buffer.from(b).toString("base64url");
const entries=new Map();
const store={async put(k,v){if(entries.has(k))return false;entries.set(k,v);return true;},async get(k){return entries.get(k);},async consume(k){const v=entries.get(k);entries.delete(k);return v;},async update(k,p,n){if(entries.get(k).revision!==p.revision)return false;entries.set(k,n);return true;}};
(async()=>{
 const origin="https://app.test", req={headers:{host:"app.test",origin},socket:{encrypted:true,remoteAddress:"192.0.2.1"}};
 const service=new Passkeys({store,rpID:"app.test",origin});
 await assert.rejects(()=>service.handle("register/options",{ticket:"invalid"},req));
 const ticket=await service.enrollmentTicket("user-1","Test user");
 const registration=await service.handle("register/options",{ticket},req);
 await assert.rejects(()=>service.handle("register/options",{ticket},req));
 const pair=crypto.generateKeyPairSync("ec",{namedCurve:"P-256"}),jwk=pair.publicKey.export({format:"jwk"});
 const cose=encodeCBOR(new Map([[1,2],[3,-7],[-1,1],[-2,Buffer.from(jwk.x,"base64url")],[-3,Buffer.from(jwk.y,"base64url")]]));
 const credential=crypto.randomBytes(32),length=Buffer.alloc(2);length.writeUInt16BE(credential.length);
 const rpHash=crypto.createHash("sha256").update("app.test").digest();
 const clientData=Buffer.from(JSON.stringify({type:"webauthn.create",challenge:registration.options.challenge,origin}));
 const authData=Buffer.concat([rpHash,Buffer.from([0x45]),Buffer.alloc(4),Buffer.alloc(16),length,credential,Buffer.from(cose)]);
 const response={id:b64(credential),rawId:b64(credential),type:"public-key",clientExtensionResults:{},response:{clientDataJSON:b64(clientData),attestationObject:b64(encodeCBOR(new Map([["fmt","none"],["attStmt",new Map()],["authData",authData]]))),transports:["internal"]}};
 assert.deepEqual(await service.handle("register/verify",{id:registration.id,response},req),{registered:true});
 const options=await service.handle("authenticate/options",{action:"login"},req);
 const data=Buffer.from(JSON.stringify({type:"webauthn.get",challenge:options.options.challenge,origin}));
 const counter=Buffer.alloc(4);counter.writeUInt32BE(1);
 const auth=Buffer.concat([rpHash,Buffer.from([5]),counter]);
 const signature=crypto.sign("sha256",Buffer.concat([auth,crypto.createHash("sha256").update(data).digest()]),pair.privateKey);
 const assertion={id:b64(credential),rawId:b64(credential),type:"public-key",clientExtensionResults:{},response:{clientDataJSON:b64(data),authenticatorData:b64(auth),signature:b64(signature)}};
 const result=await service.handle("authenticate/verify",{id:options.id,response:assertion},req);
 assert(verifyToken(result.token,{action:"login",origin,host:origin,clientIP:"192.0.2.1"}).valid);
 await assert.rejects(()=>service.handle("authenticate/verify",{id:options.id,response:assertion},req));
 console.log("Real WebAuthn registration, signature verification, provisioning and replay tests passed");
})().catch(e=>{console.error(e);process.exitCode=1;});
